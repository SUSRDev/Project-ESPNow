def shorten(s: str, n: int) -> str:
    s = re.sub(r"\s+", "", s)
    s = s.replace("……", "…").replace("...", "…")
    if len(s) <= n:
        return s
    return s[: n - 1] + "…"

def parse_scrapes():
    out = []
    files = list(AGENT.glob("*.txt")) if AGENT.exists() else []
    for fp in files:
        try:
            text = fp.read_text(encoding="utf-8", errors="ignore")
        except Exception:
            continue
        # pattern 汤面：... 汤底：...
        for m in re.finditer(
            r"汤面\s*\d*[：:．\.]?\s*(.+?)\s*汤底\s*\d*[：:．\.]?\s*(.+?)(?=\n\s*汤面|\n\s*\d+[、．.]|\n#|\Z)",
            text,
            re.S,
        ):
            face, truth = m.group(1).strip(), m.group(2).strip()
            face = re.sub(r"\s+", "", face)
            truth = re.sub(r"\s+", "", truth)
            if len(face) < 8 or len(truth) < 8:
                continue
            out.append((face, truth))
        # numbered blocks
        for m in re.finditer(
            r"\d+[、.．]\s*([^\n]{4,80})\n+汤面[：:]\s*(.+?)\n+汤底[：:]\s*(.+?)(?=\n\d+[、.．]|\n#|\Z)",
            text,
            re.S,
        ):
            title, face, truth = m.group(1), m.group(2), m.group(3)
            face = re.sub(r"\s+", "", face) or title
            truth = re.sub(r"\s+", "", truth)
            if len(truth) >= 8:
                out.append((face, truth))
    return out

def guess_diff(face: str, truth: str) -> int:
    hard_kw = ["香水", "杀手", "外婆", "娃娃", "蛆", "绑", "复仇", "精分", "割", "尸", "毒", "变态"]
    easy_kw = ["打嗝", "电梯", "伞", "生了", "忠犬", "十块", "一百", "蚊香", "天窗"]
    t = face + truth
    if any(k in t for k in hard_kw):
        return 2
    if any(k in t for k in easy_kw):
        return 0
    return 1

def dedupe_key(face: str) -> str:
    # normalize
    s = re.sub(r"[，。！？、；：…\s]", "", face)[:24]
    return s

